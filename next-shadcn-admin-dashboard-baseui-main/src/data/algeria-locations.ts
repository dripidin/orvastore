/**
 * Recalculates shipping fee based on original shipment origin hub: بسكرة (Wilaya 07)
 */
export function calculateShippingFeeFromOrigin(
  wilayaInput: string,
  deliveryTypeInput: string
): ShippingCalculationResult {
  const originStr = "بسكرة (07 - Biskra Hub)";

  if (!wilayaInput) {
    return {
      success: false,
      originHub: originStr,
      wilayaId: null,
      wilayaName: null,
      isStopDesk: false,
      shippingFee: null,
      shippingFeeFormatted: null,
      deliveryTime: null,
      error: "يرجى تحديد الولاية لحساب رسوم الشحن."
    };
  }

  const codeStr = findWilayaCodeByName(wilayaInput);
  if (!codeStr) {
    return {
      success: false,
      originHub: originStr,
      wilayaId: null,
      wilayaName: null,
      isStopDesk: false,
      shippingFee: null,
      shippingFeeFormatted: null,
      deliveryTime: null,
      error: `تعذر العثور على تسعيرة معتمدة للولاية: "${wilayaInput}". يرجى التحقق من القائمة.`
    };
  }

  const wId = parseInt(codeStr, 10);
  const tariff = ALGERIA_SHIPPING_TARIFFS[wId];

  if (!tariff) {
    return {
      success: false,
      originHub: originStr,
      wilayaId: wId,
      wilayaName: null,
      isStopDesk: false,
      shippingFee: null,
      shippingFeeFormatted: null,
      deliveryTime: null,
      error: `لا توجد تسعيرة مسجلة للولاية رقم ${wId} في جدول Tarif_Biskra.txt.`
    };
  }

  const normDeliv = (deliveryTypeInput || "").toLowerCase();
  const isStopDesk = normDeliv.includes("مكتب") || normDeliv.includes("stopdesk") || normDeliv.includes("point");

  if (isStopDesk) {
    if (tariff.stopdesk === null) {
      return {
        success: false,
        originHub: originStr,
        wilayaId: wId,
        wilayaName: tariff.name,
        isStopDesk: true,
        shippingFee: null,
        shippingFeeFormatted: null,
        deliveryTime: tariff.time,
        stopDeskUnavailable: true,
        warning: `خدمة التوصيل للمكتب (Stop Desk) غير متوفرة في ولاية (${tariff.name}) وفق تسعيرة Redex. يجب اختيار توصيل للمنزل.`
      };
    }

    return {
      success: true,
      originHub: originStr,
      wilayaId: wId,
      wilayaName: tariff.name,
      isStopDesk: true,
      shippingFee: tariff.stopdesk,
      shippingFeeFormatted: `${tariff.stopdesk} د.ج`,
      deliveryTime: tariff.time
    };
  }

  // Domicile delivery
  return {
    success: true,
    originHub: originStr,
    wilayaId: wId,
    wilayaName: tariff.name,
    isStopDesk: false,
    shippingFee: tariff.domicile,
    shippingFeeFormatted: `${tariff.domicile} د.ج`,
    deliveryTime: tariff.time
  };
}
