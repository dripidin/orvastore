export function findWilayaCodeByName(wilayaName: string): string | null {
  if (!wilayaName) return null;
  const trimmed = wilayaName.trim();
  // Check direct code match e.g. "16 - Alger" or "16"
  const match = trimmed.match(/^(\d{1,2})/);
  if (match) {
    const num = parseInt(match[1], 10);
    if (num >= 1 && num <= 58) return String(num);
  }
  // Check by Arabic name
  const found = ALGERIA_WILAYAS.find(w => trimmed.includes(w.arName) || w.name.includes(trimmed));
  return found ? found.id : null;
}

